"""Generate small bundled prop OBJs (v/vt/vn + triangulated f faces).

Winding is verified programmatically: every emitted triangle must face
outward (dot(cross(b-a, c-a), outward) > 0), matching the renderer's
front-face convention (counter-clockwise as seen in NDC).
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

Vec = tuple[float, float, float]


def sub(a: Vec, b: Vec) -> Vec:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a: Vec, b: Vec) -> Vec:
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def dot(a: Vec, b: Vec) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def norm(a: Vec) -> Vec:
    length = math.sqrt(dot(a, a))
    assert length > 0.0
    return (a[0] / length, a[1] / length, a[2] / length)


class Builder:
    def __init__(self) -> None:
        self.positions: list[Vec] = []
        self.uvs: list[tuple[float, float]] = []
        self.normals: list[Vec] = []
        self.faces: list[tuple[int, int, int]] = []  # 1-based unified indices

    def vertex(self, p: Vec, uv: tuple[float, float], n: Vec) -> int:
        self.positions.append(p)
        self.uvs.append(uv)
        self.normals.append(n)
        return len(self.positions)

    def triangle(self, a: int, b: int, c: int, outward: Vec) -> None:
        pa, pb, pc = (self.positions[i - 1] for i in (a, b, c))
        facing = cross(sub(pb, pa), sub(pc, pa))
        assert dot(facing, outward) > 0.0, (a, b, c, facing, outward)
        self.faces.append((a, b, c))

    def quad(self, corners: list[Vec], outward: Vec) -> None:
        n = norm(outward)
        uvs = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)]
        ids = [self.vertex(p, uv, n) for p, uv in zip(corners, uvs)]
        self.triangle(ids[0], ids[1], ids[2], outward)
        self.triangle(ids[0], ids[2], ids[3], outward)


def box(half: float) -> Builder:
    b = Builder()
    h = half
    b.quad([(-h, -h, h), (h, -h, h), (h, h, h), (-h, h, h)], (0.0, 0.0, 1.0))
    b.quad([(h, -h, -h), (-h, -h, -h), (-h, h, -h), (h, h, -h)], (0.0, 0.0, -1.0))
    b.quad([(h, -h, h), (h, -h, -h), (h, h, -h), (h, h, h)], (1.0, 0.0, 0.0))
    b.quad([(-h, -h, -h), (-h, -h, h), (-h, h, h), (-h, h, -h)], (-1.0, 0.0, 0.0))
    b.quad([(h, h, -h), (-h, h, -h), (-h, h, h), (h, h, h)], (0.0, 1.0, 0.0))
    b.quad([(h, -h, h), (-h, -h, h), (-h, -h, -h), (h, -h, -h)], (0.0, -1.0, 0.0))
    return b


def pillar(sides: int, radius: float, height: float) -> Builder:
    b = Builder()
    rim = [
        (radius * math.cos(2.0 * math.pi * k / sides), radius * math.sin(2.0 * math.pi * k / sides))
        for k in range(sides)
    ]
    for k in range(sides):
        x0, z0 = rim[k]
        x1, z1 = rim[(k + 1) % sides]
        mid = ((x0 + x1) * 0.5, (z0 + z1) * 0.5)
        outward = norm((mid[0], 0.0, mid[1]))
        b.quad(
            [(x1, 0.0, z1), (x0, 0.0, z0), (x0, height, z0), (x1, height, z1)],
            outward,
        )
    for y, outward, flip in ((height, (0.0, 1.0, 0.0), False), (0.0, (0.0, -1.0, 0.0), True)):
        n = norm(outward)
        center = b.vertex((0.0, y, 0.0), (0.5, 0.5), n)
        ring = [
            b.vertex((x, y, z), (x / (2.0 * radius) + 0.5, z / (2.0 * radius) + 0.5), n)
            for x, z in rim
        ]
        for k in range(sides):
            a, c = ring[k], ring[(k + 1) % sides]
            if flip:
                b.triangle(center, a, c, outward)
            else:
                b.triangle(center, c, a, outward)
    return b


def pyramid(half: float, height: float) -> Builder:
    b = Builder()
    h = half
    b.quad([(h, 0.0, h), (-h, 0.0, h), (-h, 0.0, -h), (h, 0.0, -h)], (0.0, -1.0, 0.0))
    apex = (0.0, height, 0.0)
    base = [(-h, 0.0, h), (h, 0.0, h), (h, 0.0, -h), (-h, 0.0, -h)]
    for k in range(4):
        p0, p1 = base[k], base[(k + 1) % 4]
        outward = norm(cross(sub(p1, p0), sub(apex, p0)))
        n = outward
        a = b.vertex(p0, (0.0, 0.0), n)
        c = b.vertex(p1, (1.0, 0.0), n)
        d = b.vertex(apex, (0.5, 1.0), n)
        b.triangle(a, c, d, outward)
    return b


def write(path: Path, builder: Builder) -> None:
    with path.open("w", encoding="utf-8") as file:
        file.write(f"# {path.name}: bundled prop, generated by scripts/generate_prop_objs.py\n")
        for p in builder.positions:
            file.write(f"v {p[0]!r} {p[1]!r} {p[2]!r}\n")
        for uv in builder.uvs:
            file.write(f"vt {uv[0]!r} {uv[1]!r}\n")
        for n in builder.normals:
            file.write(f"vn {n[0]!r} {n[1]!r} {n[2]!r}\n")
        for a, c, d in builder.faces:
            file.write(f"f {a}/{a}/{a} {c}/{c}/{c} {d}/{d}/{d}\n")
    print(f"wrote {path} ({len(builder.faces)} triangles)")


def main() -> int:
    root = Path(__file__).resolve().parent.parent / "assets" / "models"
    write(root / "prop_crate.obj", box(0.5))
    write(root / "prop_pillar.obj", pillar(8, 0.5, 2.0))
    write(root / "prop_pyramid.obj", pyramid(0.5, 1.0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
